/**
 * Dialect output for SQL Server and Postgres (no server needed): query SQL from
 * the SQL Server dialect, and CREATE / ALTER from both DDL writers. Live runs
 * against real servers belong to the systems that bring the drivers.
 */
import { describe, it, expect } from 'vitest';
import { fixture } from './_utils';
import type { SelectDef } from '../schema';
import { PostgresDialect, SqlServerDialect, SqliteDialect } from '../sql/index';
import type { TableSpec } from '../ddl/index';

const people: TableSpec = {
  name: 'people',
  schema: 'app',
  columns: [
    { name: 'id', type: { kind: 'integer', big: true }, nullable: false, generated: true },
    { name: 'name', type: { kind: 'text', maxLength: 80 }, nullable: false },
    { name: 'active', type: { kind: 'bool' }, nullable: false, default: { kind: 'value', value: true } },
    { name: 'born', type: { kind: 'date' }, nullable: true },
  ],
  primaryKey: ['id'],
  foreignKeys: [],
  unique: [],
};

const changed: TableSpec = {
  ...people,
  columns: [
    { name: 'id', type: { kind: 'integer', big: true }, nullable: false, generated: true },
    { name: 'name', type: { kind: 'text', maxLength: 40 }, nullable: true },
    { name: 'active', type: { kind: 'bool' }, nullable: false },
    { name: 'team', type: { kind: 'text' }, nullable: true, values: ['red', 'blue'] },
  ],
};

describe('SQL Server dialect', () => {
  const fx = fixture();
  const select: SelectDef = {
    kind: 'select',
    fields: [{ expr: { kind: 'field-ref', source: 'user', field: 'name' }, as: 'name' }],
    from: { kind: 'type', type: 'user' },
    where: [
      { kind: 'comparison', op: 'ilike', left: { kind: 'field-ref', source: 'user', field: 'name' }, right: { kind: 'param', name: 'q' } },
      { kind: 'filters', source: 'user' },
    ],
    order: [{ expr: { kind: 'field-ref', source: 'user', field: 'age' }, dir: 'asc', nulls: 'last' }],
    limit: 10,
    offset: 20,
  };

  it('brackets, @p placeholders, OFFSET … FETCH, emulated NULLS LAST, and (1 = 1)', () => {
    const out = fx.engine.toSQL(select, 'sqlserver', { params: { q: 'a%' } });
    expect(out.sql).toBe(
      'SELECT [user].[name] AS [name] FROM [user] AS [user] WHERE LOWER([user].[name]) LIKE LOWER(@p1) AND (1 = 1) ' +
        'ORDER BY CASE WHEN [user].[age] IS NULL THEN 1 ELSE 0 END, [user].[age] ASC OFFSET 20 ROWS FETCH NEXT 10 ROWS ONLY',
    );
    expect(out.params).toEqual(['a%']);
  });

  it('pages an unordered select with a neutral ORDER BY', () => {
    const out = fx.engine.toSQL({ ...select, order: [], where: [], offset: undefined }, 'sqlserver');
    expect(out.sql).toMatch(/ORDER BY \(SELECT NULL\) OFFSET 0 ROWS FETCH NEXT 10 ROWS ONLY$/u);
  });

  it('spells date parts and renamed builtins natively', () => {
    const d = new SqlServerDialect();
    const x = (s: string) => d.emitBuiltinCall(s, [d.ident('d')])?.render(d).sql;
    expect(x('year')).toBe('DATEPART(year, [d])');
    expect(x('length')).toBe('LEN([d])');
    expect(d.emitBuiltinCall('currentDate', [])?.render(d).sql).toBe('CAST(GETDATE() AS date)');
  });

  it('binds booleans as given, while SQLite binds them as 1 / 0', () => {
    expect(new SqlServerDialect().encodeParam(true)).toBe(true);
    expect(new SqliteDialect().encodeParam(true)).toBe(1);
  });
});

describe('DDL writers', () => {
  it('Postgres: CREATE TABLE with identity, constraints and a schema', () => {
    const sql = new PostgresDialect().ddl.createTable(people).sql[0];
    expect(sql).toBe(
      'CREATE TABLE "app"."people" (\n  "id" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,\n  "name" varchar(80) NOT NULL,\n' +
        '  "active" boolean NOT NULL DEFAULT TRUE,\n  "born" date,\n  CONSTRAINT "pk_people" PRIMARY KEY ("id")\n)',
    );
  });

  it('Postgres: ordered ALTER steps, narrowing and drops marked irreversible', () => {
    const steps = new PostgresDialect().ddl.alterTable(people, changed);
    expect(steps.map((s) => [s.action, s.target, s.irreversible])).toEqual([
      ['drop-column', 'born', true],
      ['add-column', 'team', false],
      ['add-constraint', 'ck_people_team', false],
      ['alter-column', 'name', true],
      ['alter-column', 'active', false],
    ]);
    expect(steps[3]?.sql).toEqual([
      'ALTER TABLE "app"."people" ALTER COLUMN "name" TYPE varchar(40) USING "name"::varchar(40)',
      'ALTER TABLE "app"."people" ALTER COLUMN "name" DROP NOT NULL',
    ]);
    expect(steps[4]?.sql).toEqual(['ALTER TABLE "app"."people" ALTER COLUMN "active" DROP DEFAULT']);
  });

  it('SQL Server: IDENTITY, named defaults, ALTER COLUMN with nullability', () => {
    const ddl = new SqlServerDialect().ddl;
    expect(ddl.createTable(people).sql[0]).toContain('[id] bigint IDENTITY(1,1) NOT NULL');
    expect(ddl.createTable(people).sql[0]).toContain('[active] bit NOT NULL CONSTRAINT [df_people_active] DEFAULT 1');
    const steps = ddl.alterTable(people, changed);
    expect(steps.find((s) => s.target === 'name')?.sql).toEqual(['ALTER TABLE [app].[people] ALTER COLUMN [name] nvarchar(40) NULL']);
    expect(steps.find((s) => s.target === 'active')?.sql).toEqual(['ALTER TABLE [app].[people] DROP CONSTRAINT [df_people_active]']);
    expect(steps.find((s) => s.action === 'add-column')?.sql).toEqual(['ALTER TABLE [app].[people] ADD [team] nvarchar(max)']);
  });

  it('reads native types and defaults back', () => {
    const pg = new PostgresDialect().ddl;
    expect(pg.readColumnType('character varying(40)')).toEqual({ kind: 'text', maxLength: 40 });
    expect(pg.readColumnType('timestamp with time zone')).toEqual({ kind: 'timestamp', timezone: true });
    expect(pg.readColumnType('numeric(10,2)')).toEqual({ kind: 'decimal', precision: 10, scale: 2 });
    expect(pg.readDefault("'free'::text")).toEqual({ kind: 'value', value: 'free' });
    expect(pg.readDefault('now()')).toEqual({ kind: 'now' });
    expect(pg.readDefault("nextval('people_id_seq'::regclass)")).toEqual({ kind: 'sql', sql: "nextval('people_id_seq'::regclass)" });
    const ms = new SqlServerDialect().ddl;
    expect(ms.readColumnType('nvarchar(max)')).toEqual({ kind: 'text' });
    expect(ms.readColumnType('uniqueidentifier')).toEqual({ kind: 'uuid' });
    expect(ms.readDefault('((0))')).toEqual({ kind: 'value', value: 0 });
    expect(ms.readDefault("(N'x')")).toEqual({ kind: 'value', value: 'x' });
    // A JSON column is nvarchar(max) on SQL Server, so it compares equal to text there.
    expect(ms.canonicalType({ kind: 'json' })).toEqual({ kind: 'text' });
  });
});
